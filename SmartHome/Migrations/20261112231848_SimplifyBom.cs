 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER bom_revision_ready AFTER INSERT ON bom_revision DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION bom_revision_ready();
